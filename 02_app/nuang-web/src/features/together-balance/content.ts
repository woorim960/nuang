import type {
  BalanceAudience,
  BalancePack,
  BalancePromptRole,
  BalanceQuestion,
  BalanceScoringTemplate,
  BalanceSensitivity,
} from "./types";

type QuestionSeed = readonly [
  prompt: string,
  optionA: string,
  optionB: string,
  subtopic: string,
];

type PackSeed = Readonly<{
  id: string;
  slug: string;
  title: string;
  description: string;
  scoringTemplate: BalanceScoringTemplate;
  defaultQuestionCount: 12 | 16 | 20;
  contentPoolVersion?: number;
  promptRole: BalancePromptRole;
  audience?: BalanceAudience;
  sensitivity?: BalanceSensitivity;
  questions: readonly QuestionSeed[];
}>;

function resultSemanticsFor(template: BalanceScoringTemplate) {
  switch (template) {
    case "taste_sync":
      return "taste_sync" as const;
    case "relationship_standard":
      return "relationship_standard_sync" as const;
    case "ideal_preference":
      return "ideal_preference_similarity" as const;
    case "reciprocal_fit":
      return "reciprocal_fit" as const;
    case "dilemma_fun":
      return "choice_chemistry" as const;
    case "discovery_only":
      return "discovery_only" as const;
  }
}

function buildPack(seed: PackSeed): BalancePack {
  const questions = seed.questions.map<BalanceQuestion>(
    ([prompt, optionA, optionB, subtopic], index) => {
      const questionNumber = String(index + 1).padStart(3, "0");
      const id = `${seed.id}_${questionNumber}`;
      const ratio = index / seed.questions.length;

      return {
        id,
        packId: seed.id,
        prompt,
        options: [
          { id: `${id}:a`, text: optionA },
          { id: `${id}:b`, text: optionB },
        ],
        subtopic,
        promptRole: seed.promptRole,
        phase:
          ratio < 0.34
            ? "familiar"
            : ratio < 0.68
              ? "everyday"
              : "conversation",
        intensity: seed.sensitivity === "personal" ? "lively" : "light",
        audience: seed.audience ?? "all",
        sensitivity: seed.sensitivity ?? "general",
        scored: true,
        highlightPriority: ratio >= 0.68 ? 3 : ratio >= 0.34 ? 2 : 1,
        conversationValue: ratio >= 0.68 ? 3 : 2,
        contentVersion: seed.contentPoolVersion ?? 1,
      };
    },
  );

  return {
    id: seed.id,
    slug: seed.slug,
    title: seed.title,
    description: seed.description,
    scoringTemplate: seed.scoringTemplate,
    resultSemantics: resultSemanticsFor(seed.scoringTemplate),
    defaultQuestionCount: seed.defaultQuestionCount,
    supportedQuestionCounts: [8, 12, 16, 20, 24],
    roundSize: 8,
    contentPoolVersion: seed.contentPoolVersion ?? 1,
    questions,
  };
}

