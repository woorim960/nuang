function replaceIdentity(text: string) {
  return text
    .replaceAll("ENAKQ", "ENAKC")
    .replaceAll("관계를 여는 지휘자", "사람과 가능성을 잇는 연결가")
    .replaceAll("E·N·A·K·Q", "E·N·A·K·C")
    .replaceAll("빠른 걱정 신호", "차분한 초기 반응")
    .replaceAll("걱정이 빠르게 올라와도", "불편함이 생겨도")
    .replaceAll("걱정이 올라와도", "불편함이 생겨도");
}

