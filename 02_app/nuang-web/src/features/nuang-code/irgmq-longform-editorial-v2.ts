function replaceIdentity(text: string) {
  return text
    .replaceAll("IRGMC", "IRGMQ")
    .replaceAll("단서로 답을 찾는 탐구자", "변화의 원인을 좇는 추적자")
    .replaceAll("I·R·G·M·C", "I·R·G·M·Q");
}

